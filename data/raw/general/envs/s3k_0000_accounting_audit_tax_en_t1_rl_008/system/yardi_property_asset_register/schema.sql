CREATE TABLE property_assets (
  asset_id TEXT PRIMARY KEY,
  property_id TEXT NOT NULL,
  case_id TEXT,
  property_display_name TEXT NOT NULL,
  asset_name TEXT NOT NULL,
  asset_class TEXT NOT NULL CHECK (asset_class IN ('LAND','BUILDING','TENANT_IMROVEMENT','SITE_IMPROVEMENT','EQUIPMENT','DISPOSITION_COST')),
  parent_asset_id TEXT,
  placed_in_service_date TEXT NOT NULL CHECK (placed_in_service_date GLOB '????-??-??'),
  depreciation_through_date TEXT CHECK (depreciation_through_date IS NULL OR depreciation_through_date GLOB '????-??-??'),
  depreciation_method TEXT NOT NULL,
  original_cost_usd INTEGER NOT NULL CHECK (original_cost_usd >= 0),
  accumulated_depreciation_usd INTEGER NOT NULL CHECK (accumulated_depreciation_usd >= 0 AND accumulated_depreciation_usd <= original_cost_usd),
  final_period_depreciation_usd INTEGER NOT NULL DEFAULT 0 CHECK (final_period_depreciation_usd >= 0),
  tax_character_code TEXT NOT NULL CHECK (tax_character_code IN ('NONDEPRECIABLE','IRC1245','IRC1250','SELLING_COST')),
  tax_basis_status TEXT NOT NULL CHECK (tax_basis_status IN ('INCLUDED','EXCLUDED','UNREVIEWED')),
  status TEXT NOT NULL CHECK (status IN ('ACTIVE','DISPOSED','RETIRED','VOID')),
  approved_flag INTEGER NOT NULL DEFAULT 0 CHECK (approved_flag IN (0,1)),
  approved_by_entity_id TEXT,
  approved_at TEXT,
  row_version INTEGER NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  FOREIGN KEY (parent_asset_id) REFERENCES property_assets(asset_id)
);

CREATE TABLE ownership_ledger (
  ledger_entry_id TEXT PRIMARY KEY,
  property_id TEXT NOT NULL,
  case_id TEXT,
  entity_id TEXT NOT NULL,
  partner_id TEXT NOT NULL,
  ledger_date TEXT NOT NULL CHECK (ledger_date GLOB '????-??-??'),
  outside_basis_usd INTEGER NOT NULL CHECK (outside_basis_usd >= 0),
  capital_account_usd INTEGER NOT NULL CHECK (capital_account_usd >= 0),
  liability_share_usd INTEGER NOT NULL CHECK (liability_share_usd >= 0),
  entry_amount_usd INTEGER NOT NULL,
  entry_type TEXT NOT NULL CHECK (entry_type IN ('OPENING_SNAPSHOT','CAPITAL_CONTRIBUTION','DISTRIBUTION','BASIS_ADJUSTMENT','DEBT_ALLOCATION','LIABILITY_RELIEF_ESTIMATE','PARTNER_SNAPSHOT','GP_INTEREST_SNAPSHOT')),
  source_asset_id TEXT,
  current_flag INTEGER NOT NULL DEFAULT 0 CHECK (current_flag IN (0,1)),
  approved_flag INTEGER NOT NULL DEFAULT 0 CHECK (approved_flag IN (0,1)),
  approved_by_entity_id TEXT,
  approved_at TEXT,
  row_version INTEGER NOT NULL DEFAULT 1 CHECK (row_version >= 1),
  FOREIGN KEY (source_asset_id) REFERENCES property_assets(asset_id)
);